    "        z_ctx = self.zmax_agg(z_flat)\n",
    "        e_ctx = self.e4_agg(e_flat)\n",
    "        fused = torch.cat([z_ctx, e_ctx], dim=1)\n",
    "        main_logits = self.classifier(fused)\n",
    "        zmax_aux_logits = self.zmax_aux_classifier(z_ctx)\n",
    "        e4_aux_logits = self.e4_aux_classifier(e_ctx)\n",
    "        return main_logits, zmax_aux_logits, e4_aux_logits\n",
