    "    train_subs = np.load(train_p, allow_pickle=True).tolist()\n",
    "    val_subs   = np.load(val_p, allow_pickle=True).tolist()\n",
    "    test_subs  = np.load(test_p, allow_pickle=True).tolist()\n",
    "    assert set(train_subs).isdisjoint(val_subs)\n",
    "    assert set(train_subs).isdisjoint(test_subs)\n",
    "    assert set(val_subs).isdisjoint(test_subs)\n",
    "    return train_subs, val_subs, test_subs\n",
