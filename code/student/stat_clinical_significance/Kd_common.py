    "def load_3way_split(split_path):\n",
    "    train_p = os.path.join(split_path, \"_train_subs.npy\")\n",
    "    val_p   = os.path.join(split_path, \"_val_subs.npy\")\n",
    "    test_p  = os.path.join(split_path, \"_test_subs.npy\")\n",
    "    for p, name in [(train_p, \"_train_subs.npy\"), (val_p, \"_val_subs.npy\"), (test_p, \"_test_subs.npy\")]:\n",
    "        if not os.path.exists(p):\n",
